"""Run the standard backend checks and write a markdown table of what actually happened (DEC-141).

    python record_checks.py --cwd backend
    python record_checks.py --cwd backend --out docs/delivery/evidence/U02.md --heading "Checks (generated)" \
        --extra "Neo4j confirm::flock /tmp/diucs-neo4j-tests.lock uv run pytest tests/integration/application/test_confirm_capacity.py -q"

Each command runs without a pipe, so its own exit code is the one recorded. The table lists the command,
the exit code and the last non-empty output line. The exit status of this script is 1 if any command failed.
Standard library only.
"""

from __future__ import annotations

import argparse
import datetime
import shlex
import subprocess
import sys
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

DEFAULT_COMMANDS: list[tuple[str, str]] = [
    ("unit and architecture tests", "uv run pytest tests/unit tests/architecture -q"),
    ("lint", "uv run ruff check ."),
    ("format", "uv run ruff format --check ."),
    ("types", "uv run mypy src"),
    ("import contracts", "uv run lint-imports"),
]


@dataclass
class Result:
    label: str
    command: str
    exit_code: int
    summary: str


Runner = Callable[[str, str], tuple[int, str]]


def run_shell(command: str, cwd: str) -> tuple[int, str]:
    done = subprocess.run(shlex.split(command), cwd=cwd, capture_output=True, text=True)
    return done.returncode, (done.stdout or "") + (done.stderr or "")


def last_line(text: str) -> str:
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    return lines[-1][:120] if lines else ""


def run_commands(commands: list[tuple[str, str]], cwd: str, runner: Runner = run_shell) -> list[Result]:
    results = []
    for label, command in commands:
        code, output = runner(command, cwd)
        results.append(Result(label, command, code, last_line(output)))
    return results


def render_table(results: list[Result], sha: str, dirty: bool, now: str) -> str:
    rows = ["| Check | Command | Exit | Last line |", "|---|---|---|---|"]
    for r in results:
        rows.append(f"| {r.label} | `{r.command}` | {r.exit_code} | {r.summary.replace('|', '/')} |")
    state = "dirty working tree" if dirty else "clean working tree"
    return f"Generated by `record_checks.py` at {now} on `{sha}` ({state}).\n\n" + "\n".join(rows) + "\n"


def replace_section(text: str, heading: str, body: str) -> str:
    marker = f"## {heading}"
    new = f"{marker}\n{body}"
    if marker not in text:
        return text.rstrip("\n") + "\n\n" + new
    start = text.index(marker)
    after = text.find("\n## ", start + len(marker))
    if after == -1:
        return text[:start] + new
    return text[:start] + new + "\n" + text[after + 1 :]


def git(args: list[str], cwd: str) -> str:
    return subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True).stdout.strip()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--cwd", default="backend")
    parser.add_argument("--out", help="evidence file to update")
    parser.add_argument("--heading", default="Checks (generated)")
    parser.add_argument("--extra", action="append", default=[], help='"label::command", repeatable')
    parser.add_argument("--only-extra", action="store_true", help="skip the standard commands")
    args = parser.parse_args(argv)
    commands = [] if args.only_extra else list(DEFAULT_COMMANDS)
    for item in args.extra:
        label, _, command = item.partition("::")
        commands.append((label.strip(), command.strip()))
    results = run_commands(commands, args.cwd, run_shell)
    sha = git(["rev-parse", "--short", "HEAD"], args.cwd)
    dirty = bool(git(["status", "--porcelain"], args.cwd))
    now = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    table = render_table(results, sha, dirty, now)
    if args.out:
        path = Path(args.out)
        path.write_text(replace_section(path.read_text(encoding="utf-8") if path.exists() else "", args.heading, table), encoding="utf-8")
    print(table)
    return 1 if any(r.exit_code != 0 for r in results) else 0


if __name__ == "__main__":
    sys.exit(main())
