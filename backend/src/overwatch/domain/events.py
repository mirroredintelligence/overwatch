_UTC_OFFSET = timedelta(0)

# Booking references are 4 digits without a leading zero: domain-rules.md section 3.2 [ASSUMED],
# generated by booking_rules.new_reference (DEC-007). Anything else, including a name, a postcode
# or a phone or NHS number, is refused before it can reach a message or a log.
_REFERENCE = re.compile(r"[1-9][0-9]{3}")
_UTC_TIMESTAMP = re.compile(
    r"[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}(\.[0-9]{1,6})?Z"
)


def _require_utc(at: datetime, field: str = "at") -> None:
    if at.tzinfo is None or at.utcoffset() != _UTC_OFFSET:
        raise ValidationFailed(field, "must be a timezone-aware UTC datetime")


def _at_text(at: datetime) -> str:
    return at.astimezone(UTC).isoformat().replace("+00:00", "Z")


def _field(payload: Mapping[str, Any], key: str) -> Any:
    if key not in payload:
        raise ValidationFailed(key, "is required")
    return payload[key]


def _text(payload: Mapping[str, Any], key: str) -> str:
    value = _field(payload, key)
    if not isinstance(value, str):
        raise ValidationFailed(key, "must be text")
    return value


def _count(payload: Mapping[str, Any], key: str) -> int:
    value = _field(payload, key)
    if not isinstance(value, int) or isinstance(value, bool):
        raise ValidationFailed(key, "must be a whole number")
    return value


def _code[E: StrEnum](payload: Mapping[str, Any], key: str, enum_cls: type[E]) -> E:
    try:
        return parse_code(enum_cls, _text(payload, key))
    except ValidationFailed as refused:
        raise ValidationFailed(key, refused.message) from None


def _optional_code[E: StrEnum](payload: Mapping[str, Any], key: str, enum_cls: type[E]) -> E | None:
    if _field(payload, key) is None:
        return None
    return _code(payload, key, enum_cls)


def _when(payload: Mapping[str, Any], key: str = "at") -> datetime:
    text = _text(payload, key)
    if _UTC_TIMESTAMP.fullmatch(text) is None:
        raise ValidationFailed(key, "must be an ISO 8601 UTC timestamp ending in Z")
    try:
        return datetime.fromisoformat(text)
    except ValueError:
        raise ValidationFailed(key, "is not an ISO 8601 timestamp") from None


