"""Builds lib/map/landRings.ts (DEC-1361) from an ONS Local Authority Districts BUC GeoJSON file.

Fetch (public, OGL v3.0), then run `python scripts/build-land-rings.py lad.json`:
  https://services1.arcgis.com/ESMARspQHYMw9BZ9/arcgis/rest/services/LAD_MAY_2025_UK_BUC/FeatureServer/0/query
  with geometry=-3.6,50.2,-1.1,51.3 (envelope), inSR=4326, outSR=4326, outFields=LAD25NM, f=geojson
"""

import io
import json
import math
import sys

TOLERANCE = 0.0015  # degrees, about 150 m
MIN_BOX_AREA = 0.0004  # square degrees: smaller islets are dropped


def thin(pts, tol):
    if len(pts) < 3:
        return pts
    a, b = pts[0], pts[-1]
    dx, dy = b[0] - a[0], b[1] - a[1]
    length = math.hypot(dx, dy)
    far, far_i = 0.0, 0
    for i in range(1, len(pts) - 1):
        p = pts[i]
        dist = (
            abs(dy * (p[0] - a[0]) - dx * (p[1] - a[1])) / length
            if length > 1e-12
            else math.hypot(p[0] - a[0], p[1] - a[1])
        )
        if dist > far:
            far, far_i = dist, i
    if far > tol:
        return thin(pts[: far_i + 1], tol)[:-1] + thin(pts[far_i:], tol)
    return [a, b]


def main(src: str) -> None:
    data = json.load(open(src, encoding="utf-8"))
    rings = []
    for feature in data["features"]:
        geometry = feature["geometry"]
        polygons = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
        for polygon in polygons:
            ring = thin(polygon[0], TOLERANCE)
            if len(ring) < 4:
                continue
            xs, ys = [p[0] for p in ring], [p[1] for p in ring]
            if (max(xs) - min(xs)) * (max(ys) - min(ys)) < MIN_BOX_AREA:
                continue
            rings.append(" ".join(f"{round(p[0], 3)},{round(p[1], 3)}" for p in ring))
    head = (
        "// Land outlines for the pilot area (DEC-1361): the outer rings of the ONS Local Authority Districts\n"
        "// (May 2025, ultra generalised, BUC) around the pilot area, thinned to about 150 m. Each ring is\n"
        '// "lon,lat lon,lat ...". Contains public sector information licensed under the Open Government\n'
        "// Licence v3.0 (Office for National Statistics). Generated by scripts/build-land-rings.py: do not edit.\n\n"
        "export const LAND_RINGS: readonly string[] = [\n"
    )
    body = "".join(f"  {json.dumps(r)},\n" for r in rings)
    with io.open("lib/map/landRings.ts", "w", encoding="utf-8", newline="\n") as out:
        out.write(head + body + "];\n")
    print(len(rings), "rings")


main(sys.argv[1])
